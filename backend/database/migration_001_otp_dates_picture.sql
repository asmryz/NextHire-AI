--  Adds: registration OTP, vacancy start/end date, profile picture.
--
--  SAFE: kuch DROP ya DELETE nahi hota. Sirf naye columns / table banti hai.
--  Dobara chal jaye to bhi koi nuqsaan nahi (IF NOT EXISTS laga hai).
--  Neon > SQL Editor mein ek dafa chalao.
-- =====================================================================

BEGIN;

-- 1. Profile picture (HR, Interviewer, Candidate sab ke liye) ----------
--    Cloudinary ka URL aur public_id (delete/replace ke liye) save hoga.
ALTER TABLE users ADD COLUMN IF NOT EXISTS profile_picture_url       VARCHAR(500);
ALTER TABLE users ADD COLUMN IF NOT EXISTS profile_picture_public_id VARCHAR(255);

-- 2. Vacancy start / end date -----------------------------------------
ALTER TABLE vacancy ADD COLUMN IF NOT EXISTS start_date DATE;
ALTER TABLE vacancy ADD COLUMN IF NOT EXISTS end_date   DATE;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_vacancy_dates') THEN
        ALTER TABLE vacancy
            ADD CONSTRAINT ck_vacancy_dates
            CHECK (start_date IS NULL OR end_date IS NULL OR end_date >= start_date);
    END IF;
END
$$;

-- 3. Email OTP (registration ke waqt, aur baad mein password reset) ---
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'otp_purpose') THEN
        CREATE TYPE otp_purpose AS ENUM ('REGISTER', 'PASSWORD_RESET');
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS email_otp (
    otp_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(150) NOT NULL,
    purpose         otp_purpose  NOT NULL DEFAULT 'REGISTER',
    otp_hash        VARCHAR(255) NOT NULL,        -- OTP bcrypt hash, asli OTP kabhi save nahi hota
    expires_at      TIMESTAMPTZ  NOT NULL,        -- e.g. now() + 10 minutes
    attempts        SMALLINT     NOT NULL DEFAULT 0,
    verified_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_email_otp_attempts CHECK (attempts BETWEEN 0 AND 10)
);
CREATE INDEX IF NOT EXISTS idx_email_otp_email ON email_otp (email, purpose, created_at DESC);

-- 4. Email log mein OTP email ki type --------------------------------
ALTER TYPE email_type_enum ADD VALUE IF NOT EXISTS 'REGISTRATION_OTP';

-- 5. n8n ko nayi table ka access --------------------------------------
GRANT SELECT, INSERT, UPDATE, DELETE ON email_otp TO n8n_user;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO n8n_user;

COMMIT;

-- Check: 4 rows aani chahiye
SELECT table_name, column_name
FROM information_schema.columns
WHERE (table_name = 'users'   AND column_name LIKE 'profile_picture%')
   OR (table_name = 'vacancy' AND column_name IN ('start_date', 'end_date'))
ORDER BY table_name, column_name;
